import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { BROWSER_CAPABILITIES, BROWSER_DRIVERS, DEPRECATED_BROWSER_DRIVERS } from "../../src/browser/driver/types.ts";
import type { BrowserCapabilities } from "../../src/browser/driver/types.ts";

const root = join(import.meta.dir, "..", "..");
const SHARED_DOMAINS = ["driver", "run", "proxy", "inspect", "flow", "runStore", "viewer", "identity", "move"];
const problems: string[] = [];
const rows = new Map<string, BrowserCapabilities>();
const capabilities = Object.keys(BROWSER_CAPABILITIES) as (keyof typeof BROWSER_CAPABILITIES)[];

for (const name of BROWSER_DRIVERS) {
  const folder = join(root, "src/browser", name);
  if (!existsSync(join(folder, "index.ts"))) {
    problems.push(`src/browser/${name}/index.ts is missing: every browser is a domain of its own`);
    continue;
  }
  const mod = (await import(join(folder, "index.ts"))) as Record<string, unknown>;
  const row = mod[`${name}Capabilities`] as BrowserCapabilities | undefined;
  if (!row) problems.push(`src/browser/${name} doesn't export ${name}Capabilities (its row of the parity table)`);
  else {
    for (const c of capabilities) if (!row[c]) problems.push(`${name}Capabilities has no "${c}" (say built, notBuilt or notApplicable, and how)`);
    rows.set(name, row);
  }
  if (typeof mod[`${name}Driver`] !== "function") problems.push(`src/browser/${name} doesn't export ${name}Driver (its BrowserDriver)`);
  if (!existsSync(join(folder, `${name}.test.ts`))) problems.push(`src/browser/${name}/${name}.test.ts is missing`);
}

for (const entry of readdirSync(join(root, "src/browser"), { withFileTypes: true })) {
  if (entry.isDirectory() && !SHARED_DOMAINS.includes(entry.name) && !(BROWSER_DRIVERS as readonly string[]).includes(entry.name)) {
    problems.push(`src/browser/${entry.name} isn't in BROWSER_DRIVERS: add it there, add it to SHARED_DOMAINS when every browser uses it, or move it out of src/browser`);
  }
}

const python = readFileSync(join(root, "python/browser/browserDriver.py"), "utf8");
const pyBrowsers = python.match(/^BROWSERS = \(([^)]*)\)/m)?.[1] ?? "";
const pyOpeners = python.match(/^OPENERS = \{([^}]*)\}/m)?.[1] ?? "";
for (const name of BROWSER_DRIVERS) {
  if (!pyBrowsers.includes(`"${name}"`)) problems.push(`python/browser/browserDriver.py BROWSERS doesn't list "${name}"`);
  if (!pyOpeners.includes(`"${name}":`)) problems.push(`python/browser/browserDriver.py OPENERS has no opener for "${name}"`);
}

const { COMMANDS } = await import("../../src/cli/runner/index.ts");
const { commandTools } = await import("../../src/mcp/server/helpers/toolsFromCommands.ts");
const { inputSchemaOf } = await import("../../src/cli/runner/helpers/commandInput.ts");
for (const name of BROWSER_DRIVERS) {
  const brand = ((await import(join(root, "src/browser", name, "types.ts"))) as Record<string, { label?: string; logo?: string } | undefined>)[`${name}Brand`];
  if (!brand?.label || !brand.logo) problems.push(`src/browser/${name}/types.ts doesn't export ${name}Brand with a label and a logo: the console shows each browser by its own logo`);
  else if (!/^\/logos\/[\w.]+$/.test(brand.logo) || !existsSync(join(root, "site/apps/web/public", brand.logo))) problems.push(`${name}Brand.logo ${brand.logo} is not a file in site/apps/web/public/logos`);
}
const localAccount = (COMMANDS as { name: string; input?: { forms: { words: string[]; flags: { name: string; values?: readonly string[] }[] }[] } }[]).find((command) => command.name === "localAccount");
const browserFlag = localAccount?.input?.forms.find((form) => form.words[0] === "add")?.flags.find((flag) => flag.name === "browser");
if (!browserFlag || (browserFlag.values ?? []).join(",") !== BROWSER_DRIVERS.join(",")) problems.push(`log localAccount add --browser doesn't take every browser in BROWSER_DRIVERS (it takes ${(browserFlag?.values ?? []).join(", ") || "nothing"}): give it values: BROWSER_DRIVERS`);
const addTool = commandTools(COMMANDS).find((entry) => entry.tool === "localAccountAdd");
const mcpBrowsers = addTool?.form ? ((inputSchemaOf(addTool.form).properties.browser as { enum?: string[] } | undefined)?.enum ?? []) : [];
if (mcpBrowsers.join(",") !== BROWSER_DRIVERS.join(",")) problems.push(`the localAccountAdd MCP tool's browser takes ${mcpBrowsers.join(", ") || "nothing"}, not every browser in BROWSER_DRIVERS`);

const START = "<!-- browsers:start · generated by `bun run browsers:docs` from src/browser/<name>/types.ts. Not edited by hand. -->";
const END = "<!-- browsers:end -->";
const mark = { built: "built", notBuilt: "**not built**", notApplicable: "n/a" } as const;
const cell = (row: BrowserCapabilities | undefined, c: (typeof capabilities)[number]) => (row?.[c] ? `${mark[row[c].status]}: ${row[c].how.replace(/\|/g, "\\|")}` : "missing");
const table = [
  START,
  "",
  `| Capability | What it means | ${BROWSER_DRIVERS.map((n) => (DEPRECATED_BROWSER_DRIVERS.includes(n) ? `${n} (deprecated)` : n)).join(" | ")} |`,
  `| --- | --- | ${BROWSER_DRIVERS.map(() => "---").join(" | ")} |`,
  ...capabilities.map((c) => `| \`${c}\` | ${BROWSER_CAPABILITIES[c]} | ${BROWSER_DRIVERS.map((n) => cell(rows.get(n), c)).join(" | ")} |`),
  "",
  END,
].join("\n");

const docsPath = join(root, "docs/browsers.md");
const docs = existsSync(docsPath) ? readFileSync(docsPath, "utf8").replace(/\r\n/g, "\n") : "";
const current = docs.includes(START) && docs.includes(END) ? docs.slice(docs.indexOf(START), docs.indexOf(END) + END.length) : null;
if (process.argv.includes("--write")) {
  if (!current) throw new Error("docs/browsers.md has no browsers:start/browsers:end markers");
  writeFileSync(docsPath, docs.replace(current, table));
  console.log("docs/browsers.md: parity table regenerated.");
} else if (current !== table) {
  problems.push("docs/browsers.md's parity table is out of date: bun run browsers:docs");
}

const notBuilt = [...rows].flatMap(([name, row]) => capabilities.filter((c) => row[c].status === "notBuilt").map((c) => `${name}.${c}`));
if (problems.length) {
  console.error(`check:browsers refused (rule 44):\n${problems.map((p) => `- ${p}`).join("\n")}`);
  process.exit(1);
}
console.log(`check:browsers OK: ${BROWSER_DRIVERS.join(", ")} each have their domain, row, driver, tests, Python opener, docs column, label and logo, and a place in log localAccount add --browser and its MCP tool.${notBuilt.length ? ` Not built yet: ${notBuilt.join(", ")}.` : ""}`);
